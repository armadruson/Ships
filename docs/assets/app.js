/* ---------- tiny DOM helper (text only, never innerHTML with data) ---------- */
function h(tag, attrs = {}, ...kids) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (k === "class") el.className = v;
    else if (k === "style") el.style.cssText = v;
    else el.setAttribute(k, v);
  }
  for (const k of kids.flat()) if (k != null) el.append(k instanceof Node ? k : document.createTextNode(k));
  return el;
}
/* Rich text: pass an array of strings and [text] tuples; tuples render bold. */
function rich(el, parts) {
  el.replaceChildren(...parts.map((p) => Array.isArray(p) ? h("b", {}, p[0]) : document.createTextNode(p)));
}

/* ---------- tooltip ---------- */
const tip = $("#tip");
function showTip(evt, title, rows) {
  tip.replaceChildren(h("div", { class: "tip-title" }, title),
    ...rows.map((r) => h("div", { class: `tip-row${r.total ? " total" : ""}` },
      h("i", { style: `background:${r.color || "transparent"}` }), h("span", {}, r.label), h("b", {}, r.value))));
  tip.hidden = false;
  moveTip(evt);
}
function moveTip(evt) {
  let x, y;
  if (evt.clientX != null && evt.type !== "focus") { x = evt.clientX; y = evt.clientY; }
  else { const b = evt.target.getBoundingClientRect(); x = b.left + b.width / 2; y = b.top; }
  const w = tip.offsetWidth, ht = tip.offsetHeight;
  let left = x + 16, top = y - ht - 12;
  if (left + w > innerWidth - 8) left = x - w - 16;
  if (top < 8) top = y + 18;
  tip.style.left = `${Math.max(8, left)}px`;
  tip.style.top = `${top}px`;
}
const hideTip = () => { tip.hidden = true; };

function legend(el, items, kind = "rect") {
  el.replaceChildren(...items.map(([label, color]) =>
    h("span", {}, h("i", { class: kind === "line" ? "line" : "", style: `background:${color}` }), label)));
}

/* Responsive SVG scaffold: returns {svg, W, H}. Re-render on resize. */
function frame(el, height) {
  el.replaceChildren();
  const W = el.clientWidth, H = height || parseInt(getComputedStyle(el).getPropertyValue("--h")) || 300;
  const svg = d3.select(el).append("svg").attr("width", W).attr("height", H).attr("viewBox", `0 0 ${W} ${H}`);
  return { svg, W, H };
}
const renderers = [];
function register(fn) { renderers.push(fn); fn(); }
let rt;
addEventListener("resize", () => { clearTimeout(rt); rt = setTimeout(() => renderers.forEach((f) => f()), 150); });

function yGrid(g, y, W, left, ticks, format) {
  const t = g.append("g").attr("class", "grid");
  y.ticks(ticks).forEach((v) => {
    t.append("line").attr("x1", left).attr("x2", W).attr("y1", y(v)).attr("y2", y(v))
      .attr("class", v === 0 ? "axis-base" : null);
    t.append("text").attr("x", left - 10).attr("y", y(v)).attr("dy", "0.32em").attr("text-anchor", "end").text(format(v));
  });
}

/* Column path: 4px rounded top, square at the baseline. */
function colPath(x, y0, w, y1, r = 4) {
  const hgt = y0 - y1;
  if (hgt <= 0) return "";
  r = Math.min(r, hgt, w / 2);
  return `M${x},${y0}V${y1 + r}Q${x},${y1} ${x + r},${y1}H${x + w - r}Q${x + w},${y1} ${x + w},${y1 + r}V${y0}Z`;
}
/* Horizontal bar: rounded right end, square at the baseline. */
function barPath(x0, y, x1, hgt, r = 4) {
  const w = x1 - x0;
  if (w <= 0) return "";
  r = Math.min(r, w, hgt / 2);
  return `M${x0},${y}H${x1 - r}Q${x1},${y} ${x1},${y + r}V${y + hgt - r}Q${x1},${y + hgt} ${x1 - r},${y + hgt}H${x0}Z`;
}

/* ==========================================================================
   Stacked columns (index + fleet mix)
   ========================================================================== */
function stackedColumns(el, { rows, keys, colors, value, format, percent = false, annotate = null, tipTitle }) {
  const { svg, W, H } = frame(el);
  const m = { t: 34, r: 8, b: 30, l: percent ? 44 : 56 };
  const data = rows.filter((r) => value(r, keys[0]) != null);
  const totals = data.map((r) => d3.sum(keys, (k) => value(r, k)));
  const x = d3.scaleBand().domain(data.map((r) => r.year)).range([m.l, W - m.r]).padding(0.28);
  const y = d3.scaleLinear().domain([0, percent ? 1 : d3.max(totals) * (annotate ? 1.12 : 1)]).nice().range([H - m.b, m.t]);
  yGrid(svg, y, W - m.r, m.l, 5, percent ? (v) => pct(v) : format);

  const bw = Math.min(x.bandwidth(), 44);
  const gap = 2;
  data.forEach((r, i) => {
    const cx = x(r.year) + (x.bandwidth() - bw) / 2;
    const tot = totals[i];
    let acc = 0;
    const g = svg.append("g").attr("class", "mark");
    keys.forEach((k, ki) => {
      const v = value(r, k) / (percent ? tot : 1);
      if (!v) return;
      const yb = y(acc), yt = y(acc + v);
      const top = keys.slice(ki + 1).every((kk) => !value(r, kk));
      const y0 = yb - (acc > 0 ? gap : 0);
      if (y0 - yt > 0.5) {
        g.append("path").attr("fill", colors[k])
          .attr("d", top ? colPath(cx, y0, bw, yt) : `M${cx},${y0}V${yt}H${cx + bw}V${y0}Z`);
      }
      acc += v;
    });
    svg.append("text").attr("x", x(r.year) + x.bandwidth() / 2).attr("y", H - m.b + 18).attr("text-anchor", "middle")
      .text(W < 560 ? `’${String(r.year).slice(2)}` : r.year);
    // hit target: whole band, full height
    svg.append("rect").attr("class", "hit").attr("x", x(r.year)).attr("width", x.bandwidth()).attr("y", m.t).attr("height", H - m.t - m.b)
      .attr("tabindex", 0).attr("aria-label", `${r.year}: ${format(tot)}`)
      .on("pointerenter focus", (e) => {
        el.classList.add("dim"); g.classed("on", true);
        showTip(e, tipTitle(r), [...keys].reverse().map((k) => ({
          color: colors[k], label: k,
          value: percent ? pct(value(r, k) / tot) : format(value(r, k)),
        })).concat([{ label: "Total", value: format(tot), total: true }]));
      })
      .on("pointermove", moveTip)
      .on("pointerleave blur", () => { el.classList.remove("dim"); g.classed("on", false); hideTip(); });
  });

  if (annotate && !percent) {
    annotate.forEach(({ year, text }) => {
      const i = data.findIndex((r) => r.year === year);
      if (i < 0) return;
      const cx = x(year) + x.bandwidth() / 2, top = y(totals[i]);
      const anchor = i > data.length * 0.6 ? "end" : i < data.length * 0.25 ? "start" : "middle";
      svg.append("line").attr("class", "annot-line").attr("x1", cx).attr("x2", cx).attr("y1", top - 6).attr("y2", top - 16);
      svg.append("text").attr("class", "annot").attr("x", cx + (anchor === "start" ? -bw / 2 : anchor === "end" ? bw / 2 : 0))
        .attr("y", top - 22).attr("text-anchor", anchor).text(text);
    });
  }
}

/* ==========================================================================
   Line chart with crosshair (share, mismatch)
   ========================================================================== */
function lineChart(el, { years, series, domain, format, band = null, endLabels = true }) {
  const { svg, W, H } = frame(el);
  const m = { t: 16, r: endLabels ? 56 : 12, b: 30, l: 44 };
  const x = d3.scaleLinear().domain(d3.extent(years)).range([m.l, W - m.r]);
  const all = series.flatMap((s) => s.values.filter((v) => v != null));
  const y = d3.scaleLinear().domain(domain || [0, d3.max(all)]).nice().range([H - m.b, m.t]);
  yGrid(svg, y, W - m.r, m.l, 4, format);
  const step = W < 480 ? 3 : 2;
  const lastX = x(years.at(-1));
  years.forEach((yr, i) => {
    const isLast = i === years.length - 1;
    if (isLast || (i % step === 0 && lastX - x(yr) > 40))
      svg.append("text").attr("x", x(yr)).attr("y", H - m.b + 18).attr("text-anchor", "middle").text(yr);
  });

  if (band) {
    const area = d3.area().defined((d) => d.lo != null).x((d) => x(d.year)).y0((d) => y(d.lo)).y1((d) => y(d.hi)).curve(d3.curveMonotoneX);
    svg.append("path").attr("d", area(band.values)).attr("fill", band.color).attr("fill-opacity", 0.14);
  }
  const line = d3.line().defined((d) => d[1] != null).x((d) => x(d[0])).y((d) => y(d[1])).curve(d3.curveMonotoneX);
  series.forEach((s) => {
    const pts = years.map((yr, i) => [yr, s.values[i]]);
    const p = svg.append("path").attr("d", line(pts)).attr("fill", "none").attr("stroke", s.color).attr("stroke-width", 2)
      .attr("stroke-linejoin", "round").attr("stroke-linecap", "round");
    if (!REDUCED) {
      const len = p.node().getTotalLength();
      p.attr("stroke-dasharray", `${len} ${len}`).attr("stroke-dashoffset", len)
        .transition().duration(1400).ease(d3.easeCubicOut).attr("stroke-dashoffset", 0)
        .on("end", () => p.attr("stroke-dasharray", null));
    }
    const last = pts.filter((d) => d[1] != null).at(-1);
    svg.append("circle").attr("cx", x(last[0])).attr("cy", y(last[1])).attr("r", 4.5).attr("fill", s.color)
      .attr("stroke", css("--deep")).attr("stroke-width", 2);
    if (endLabels) svg.append("text").attr("class", "val").attr("x", x(last[0]) + 10).attr("y", y(last[1])).attr("dy", "0.32em").text(format(last[1]));
  });

  const cross = svg.append("line").attr("class", "crosshair").attr("y1", m.t).attr("y2", H - m.b).style("display", "none");
  const dots = series.map((s) => svg.append("circle").attr("r", 4.5).attr("fill", s.color).attr("stroke", css("--deep")).attr("stroke-width", 2).style("display", "none"));
  svg.append("rect").attr("class", "hit").attr("x", m.l).attr("y", m.t).attr("width", W - m.l - m.r).attr("height", H - m.t - m.b)
    .on("pointermove pointerenter", (e) => {
      const [px] = d3.pointer(e);
      const i = d3.minIndex(years, (yr) => Math.abs(x(yr) - px));
      const yr = years[i];
      cross.attr("x1", x(yr)).attr("x2", x(yr)).style("display", null);
      series.forEach((s, si) => {
        const v = s.values[i];
        dots[si].style("display", v == null ? "none" : null).attr("cx", x(yr)).attr("cy", v == null ? 0 : y(v));
      });
      const rows = series.map((s) => ({ color: s.color, label: s.name, value: s.values[i] == null ? "n/a" : format(s.values[i]) }));
      if (band && band.values[i].lo != null) rows.push({ label: band.name, value: `${band.values[i].lo}–${band.values[i].hi}` });
      showTip(e, String(yr), rows);
    })
    .on("pointerleave", () => { cross.style("display", "none"); dots.forEach((d) => d.style("display", "none")); hideTip(); });
}

