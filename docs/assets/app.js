async function logbook(stats) {
  const reg = await d3.json("data/ships.json");
  const C = Object.fromEntries(reg.columns.map((c, i) => [c, i]));
  const SA = new Set(["India", "Bangladesh", "Pakistan"]);
  const regionOf = (c) => (SA.has(c) ? "South Asia" : c === "Turkey" || c === "China" ? c : c ? "Rest of world" : "");
  const rows = reg.rows.map((r) => ({ r, hay: [r[C.name], r[C.imo], r[C.owner_country], r[C.flag], r[C.place], r[C.country], r[C.type_raw]].join(" ").toLowerCase(), region: regionOf(r[C.country]) }));

  const fy = $("#f-year"), fc = $("#f-cat"), fr = $("#f-region");
  [...new Set(reg.rows.map((r) => r[C.year]))].forEach((y) => fy.append(h("option", { value: y }, String(y))));
  stats.categories.forEach((c) => fc.append(h("option", { value: c }, c)));
  stats.regions.forEach((c) => fr.append(h("option", { value: c }, c)));

  const PAGE = 25;
  let page = 0, hits = rows;
  const body = $("#log-body");
  const render = () => {
    const pages = Math.max(1, Math.ceil(hits.length / PAGE));
    page = Math.min(page, pages - 1);
    const slice = hits.slice(page * PAGE, page * PAGE + PAGE);
    body.replaceChildren(...(slice.length ? slice.map(({ r }) => h("tr", {},
      h("td", {}, String(r[C.year])),
      h("td", {}, h("span", { class: "ship-name" }, r[C.name]), h("span", { class: "imo" }, `IMO ${r[C.imo]}`)),
      h("td", {}, h("span", { class: "pill", title: r[C.type_raw] }, h("i", { style: `background:${CAT_COLOR[r[C.category]]}` }), r[C.category])),
      h("td", { class: "num" }, r[C.gt] === "" ? "—" : fmt(r[C.gt])),
      h("td", { class: "num" }, String(r[C.built] || "—")),
      h("td", {}, r[C.flag] || "—"),
      h("td", {}, r[C.owner_country] || "—"),
      h("td", {}, [r[C.place], r[C.country]].filter(Boolean).join(", ") || "—"),
    )) : [h("tr", {}, h("td", { colspan: 8, class: "empty" }, "No ships match. Either your search is too specific, or that one got away."))]));
    $("#log-count").textContent = `${fmt(hits.length)} ${hits.length === 1 ? "ship" : "ships"}`;
    $("#page").textContent = `${page + 1} / ${pages}`;
    $("#prev").disabled = page === 0;
    $("#next").disabled = page >= pages - 1;
  };
  let qt;
  const filter = () => {
    const q = $("#q").value.trim().toLowerCase();
    const terms = q.split(/\s+/).filter(Boolean);
    hits = rows.filter((x) =>
      (!fy.value || String(x.r[C.year]) === fy.value) &&
      (!fc.value || x.r[C.category] === fc.value) &&
      (!fr.value || x.region === fr.value) &&
      terms.every((t) => x.hay.includes(t)));
    page = 0;
    render();
  };
  $("#q").addEventListener("input", () => { clearTimeout(qt); qt = setTimeout(filter, 120); });
  [fy, fc, fr].forEach((s) => s.addEventListener("change", filter));
  $("#prev").addEventListener("click", () => { page--; render(); });
  $("#next").addEventListener("click", () => { page++; render(); });
  render();
}

