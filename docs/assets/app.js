const ATLAS_NAMES = { "United States": "United States of America", "Turkey": "Turkey", "South Korea": "South Korea",
  "Russia": "Russia", "Dominican Republic": "Dominican Rep.", "Czech Republic": "Czechia", "Cote d'Ivoire": "Côte d'Ivoire" };

// Label offsets (px at 1000px width) that keep the crowded South Asian callouts apart.
const CALLOUT = { "Alang": [-70, 70], "Chattogram": [60, 70], "Gadani": [15, -85], "Aliağa": [-20, -70], "Jiangyin": [60, -45] };

async function mapChart(el, stats) {
  let world;
  try {
    world = await d3.json("https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json");
  } catch { el.textContent = "Map unavailable offline."; return; }
  const land = topojson.feature(world, world.objects.countries);
  const byName = new Map(land.features.map((f) => [f.properties.name, f]));
  // Yards with coordinates + one bubble per remaining country at its centroid.
  const points = stats.yards.map((d) => ({ ...d, label: d.name }));
  stats.countries_other.forEach((c) => {
    const f = byName.get(ATLAS_NAMES[c.country] || c.country);
    if (!f) return;
    const [lon, lat] = d3.geoCentroid(f);
    points.push({ name: `${c.country} (other yards)`, country: c.country, ships: c.ships, lon, lat, label: c.country });
  });
  points.sort((a, b) => b.ships - a.ships);
  const total = stats.totals.ships;

  register(() => {
    const { svg, W, H } = frame(el);
    const proj = d3.geoEqualEarth().rotate([-20, 0]).fitExtent([[10, 10], [W - 10, H - 10]], { type: "Sphere" });
    // zoom a touch toward the busy half of the world on wide screens
    if (W > 700) proj.scale(proj.scale() * 1.12).translate([W / 2 - W * 0.02, H / 2 + H * 0.06]);
    const path = d3.geoPath(proj);
    svg.append("path").attr("class", "sphere").attr("d", path({ type: "Sphere" }));
    svg.append("path").attr("class", "graticule").attr("d", path(d3.geoGraticule10()));
    svg.append("g").selectAll("path").data(land.features).join("path").attr("class", "land").attr("d", path);
    const r = d3.scaleSqrt().domain([0, points[0].ships]).range([0, Math.max(14, Math.min(30, W / 36))]);
    const g = svg.append("g");
    points.forEach((p, i) => {
      const [cx, cy] = proj([p.lon, p.lat]);
      const rad = Math.max(2.2, r(p.ships));
      if (i < 4 && !REDUCED) g.append("circle").attr("class", "ring").attr("cx", cx).attr("cy", cy).attr("r", rad).style("animation-delay", `${i * 0.7}s`);
      g.append("circle").attr("class", "bubble").attr("cx", cx).attr("cy", cy).attr("r", rad).attr("tabindex", 0)
        .attr("aria-label", `${p.name}: ${fmt(p.ships)} ships`)
        .on("pointerenter focus", (e) => showTip(e, p.country, [
          { color: css("--flare"), label: p.name, value: fmt(p.ships) },
          { label: "Share of all ships", value: pct(p.ships / total, 1) },
        ]))
        .on("pointermove", moveTip).on("pointerleave blur", hideTip);
      if (rad > 6) g.append("circle").attr("class", "bubble-core").attr("cx", cx).attr("cy", cy).attr("r", 1.8);
    });
    // Callouts for the biggest yards, pushed out into open water along a fixed bearing.
    const k = Math.min(1.4, W / 1000);
    const labelled = points.slice(0, W < 600 ? 3 : 5);
    labelled.forEach((p) => {
      const [cx, cy] = proj([p.lon, p.lat]);
      const [dx, dy] = (CALLOUT[p.label] || [40, -40]).map((v) => v * k);
      const ang = Math.atan2(dy, dx), rad = Math.max(2.2, r(p.ships));
      const tx = cx + dx, ty = cy + dy, anchor = dx < 0 ? "end" : "start";
      g.append("line").attr("class", "annot-line").attr("x1", cx + Math.cos(ang) * rad).attr("y1", cy + Math.sin(ang) * rad)
        .attr("x2", tx).attr("y2", ty);
      const off = dx < 0 ? -6 : 6;
      g.append("text").attr("class", "map-label").attr("x", tx + off).attr("y", ty - 2).attr("text-anchor", anchor).text(p.label);
      g.append("text").attr("class", "map-label-sub").attr("x", tx + off).attr("y", ty + 12).attr("text-anchor", anchor).text(`${fmt(p.ships)} ships`);
    });
  });
}

/* ==========================================================================
   Destination rows with shared-scale mini columns
   ========================================================================== */
function destRows(el, stats) {
  const years = stats.annual.map((a) => a.year);
  const max = d3.max(stats.destinations, (d) => d3.max(d.by_year));
  const regionOf = (c) => ["India", "Bangladesh", "Pakistan"].includes(c) ? "South Asia" : ["Turkey", "China"].includes(c) ? c : "Rest of world";
  el.replaceChildren();
  const sparks = [];
  stats.destinations.forEach((d) => {
    const spark = h("div", { class: "chart dest-spark", style: "--h:54px" });
    el.append(h("div", { class: "dest-row" },
      h("div", { class: "dest-name" }, h("i", { style: `background:${REGION_COLOR[regionOf(d.country)]}` }), d.country),
      spark,
      h("div", { class: "dest-total" }, fmt(d.ships), h("small", {}, "SHIPS"))));
    sparks.push([spark, d]);
  });
  register(() => sparks.forEach(([spark, d]) => {
    const { svg, W, H } = frame(spark, 54);
    const x = d3.scaleBand().domain(years).range([0, W]).padding(0.25);
    const y = d3.scaleLinear().domain([0, max]).range([H - 2, 4]);
    const color = REGION_COLOR[regionOf(d.country)];
    svg.append("line").attr("class", "axis-base").attr("x1", 0).attr("x2", W).attr("y1", H - 1.5).attr("y2", H - 1.5).attr("stroke", css("--axis"));
    d.by_year.forEach((v, i) => {
      const bw = Math.min(x.bandwidth(), 22);
      const bx = x(years[i]) + (x.bandwidth() - bw) / 2;
      svg.append("path").attr("class", "mark").attr("fill", color).attr("d", colPath(bx, H - 2, bw, y(v), 3));
      svg.append("rect").attr("class", "hit").attr("x", x(years[i])).attr("width", x.bandwidth()).attr("y", 0).attr("height", H)
        .on("pointerenter", (e) => showTip(e, `${d.country} · ${years[i]}`, [{ color, label: "Ships broken", value: fmt(v) }]))
        .on("pointermove", moveTip).on("pointerleave", hideTip);
    });
  }));
}

